def convert_logo(png_path):
    img = Image.open(png_path).convert("L")
    # Content bbox: pixels darker than the threshold.
    mask = img.point(lambda v: 255 if v < CROP_THRESHOLD else 0)
    bbox = mask.getbbox()
    if bbox is None:
        raise ValueError("no content found in " + str(png_path))
    img = img.crop(bbox).resize((LOGO_W, LOGO_H), Image.LANCZOS)
    pix = img.tobytes()
    out = bytearray()
    for y in range(LOGO_H):
        row = pix[y * LOGO_W:(y + 1) * LOGO_W]
        for x in range(0, LOGO_W, 2):
            hi = (255 - row[x]) >> 4
            lo = (255 - row[x + 1]) >> 4
            out.append((hi << 4) | lo)
    return bytes(out)


def font_bytes():
    return bytes(b for glyph in FONT8X8 for b in glyph)


def main(argv):
    if len(argv) != 3:
        sys.stderr.write("usage: make_assets.py <png> <outdir>\n")
        return 2
    png, outdir = argv[1], argv[2]
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "logo.raw"), "wb") as f:
        f.write(convert_logo(png))
    with open(os.path.join(outdir, "font.raw"), "wb") as f:
        f.write(font_bytes())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
