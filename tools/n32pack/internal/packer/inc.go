package packer

import "fmt"

// assetsInc returns the include file; ids follow the INDX order (RSCV = 0, assets from 1)
func assetsInc(m *Manifest, manifestName string) []byte {
	inc := fmt.Appendf(nil, "# assets.inc (generated by n32pack from %s, do not edit)\n", manifestName)
	for i, a := range m.Assets {
		inc = fmt.Appendf(inc, ".equ ASSET_%s, %d\n", a.Name, i+1)
	}
	return inc
}
