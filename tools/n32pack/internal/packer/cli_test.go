const runManifest = `{
	"name": "Run Test",
	"regions": ["europe"],
	"date": "2026-03-01T12:00:00Z",
	"rscv": "game.rscv",
	"assets": [
		{"name": "TILES", "type": "TILS", "file": "tiles.bin"},
		{"name": "PAL", "type": "TPAL", "file": "pal.bin"}
	]
}`

// runDir writes the manifest and files in a new temporary directory and returns the manifest path
func runDir(t *testing.T, files map[string][]byte) string {
	t.Helper()
	dir := t.TempDir()
	for name, data := range files {
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	path := filepath.Join(dir, "game.json")
	if err := os.WriteFile(path, []byte(runManifest), 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

const runInc = "# assets.inc (generated by n32pack from game.json, do not edit)\n" +
	".equ ASSET_TILES, 1\n" +
	".equ ASSET_PAL, 2\n"

func TestRunIncOnly(t *testing.T) {
	manifest := runDir(t, nil) // no game.rscv, no asset files
	inc := filepath.Join(filepath.Dir(manifest), "assets.inc")
	var stderr bytes.Buffer
	if code := Run([]string{"-inc", inc, manifest}, &stderr); code != 0 {
		t.Fatalf("exit %d: %s", code, stderr.String())
	}
	got, err := os.ReadFile(inc)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != runInc {
		t.Errorf("assets.inc =\n%s", got)
	}
}

func TestRunPack(t *testing.T) {
	manifest := runDir(t, map[string][]byte{
		"game.rscv": testRscv(),
		"tiles.bin": {1, 2, 3},
		"pal.bin":   {4, 5},
	})
	dir := filepath.Dir(manifest)
	out := filepath.Join(dir, "game.n32")
	inc := filepath.Join(dir, "assets.inc")
	var stderr bytes.Buffer
	if code := Run([]string{"-o", out, "-inc", inc, manifest}, &stderr); code != 0 {
		t.Fatalf("exit %d: %s", code, stderr.String())
	}
	file, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	c := readCart(t, file)
	if len(c.indx) != 3 || c.indx[1].typ != "TILS" || c.indx[2].typ != "TPAL" {
		t.Errorf("INDX %v", c.indx)
	}
	got, err := os.ReadFile(inc)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != runInc {
		t.Errorf("assets.inc =\n%s", got)
	}
	if stderr.Len() != 0 {
		t.Errorf("stderr: %s", stderr.String())
	}
}

func TestRunUsage(t *testing.T) {
	manifest := runDir(t, nil)
	for _, args := range [][]string{
		nil,
		{manifest},
		{"-o", "x.n32"},
		{"-o", "x.n32", manifest, manifest},
		{"-bad", manifest},
	} {
		var stderr bytes.Buffer
		if code := Run(args, &stderr); code != 2 {
			t.Errorf("%q: exit %d, want 2", args, code)
		}
		if !strings.Contains(stderr.String(), "usage: n32pack [-o game.n32] [-inc assets.inc] game.json") {
			t.Errorf("%q: stderr %q", args, stderr.String())
		}
	}
}

func TestRunErrorNoOutput(t *testing.T) {
	manifest := runDir(t, map[string][]byte{
		"game.rscv": appendChunk(nil, "RSCV", []byte{1, 2, 3}),
		"tiles.bin": {1},
		"pal.bin":   {2},
	})
	dir := filepath.Dir(manifest)
	out := filepath.Join(dir, "game.n32")
	inc := filepath.Join(dir, "assets.inc")
	var stderr bytes.Buffer
	if code := Run([]string{"-o", out, "-inc", inc, manifest}, &stderr); code != 1 {
		t.Fatalf("exit %d, want 1", code)
	}
	if !strings.HasPrefix(stderr.String(), "n32pack: ") {
		t.Errorf("stderr %q", stderr.String())
	}
	for _, p := range []string{out, inc} {
		if _, err := os.Stat(p); !os.IsNotExist(err) {
			t.Errorf("%s exists (err %v)", p, err)
		}
	}
}

