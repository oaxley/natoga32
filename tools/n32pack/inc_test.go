import (
	"strconv"
	"strings"
	"testing"
	"time"
)

func TestAssetsInc(t *testing.T) {
	m := &Manifest{Assets: []Asset{
		{Name: "LEVEL1_TILES", Type: "TILS"},
		{Name: "PAL", Type: "TPAL"},
	}}
	want := "# assets.inc (generated by n32pack from hello.json, do not edit)\n" +
		".equ ASSET_LEVEL1_TILES, 1\n" +
		".equ ASSET_PAL, 2\n"
	if got := string(assetsInc(m, "hello.json")); got != want {
		t.Errorf("assetsInc =\n%s\nwant\n%s", got, want)
	}
}

func TestAssetsIncNoAssets(t *testing.T) {
	want := "# assets.inc (generated by n32pack from game.json, do not edit)\n"
	if got := string(assetsInc(&Manifest{}, "game.json")); got != want {
		t.Errorf("assetsInc = %q, want %q", got, want)
	}
}

// TestAssetsIncMatchesIndx checks that each ASSET_X id names the INDX entry of asset X
func TestAssetsIncMatchesIndx(t *testing.T) {
	m := layoutManifest(t)
	file, err := pack(m, time.Now())
	if err != nil {
		t.Fatalf("pack: %v", err)
	}
	c := readCart(t, file)

	ids := map[string]int{}
	lines := strings.Split(strings.TrimSuffix(string(assetsInc(m, "game.json")), "\n"), "\n")
	for _, line := range lines[1:] {
		rest, ok := strings.CutPrefix(line, ".equ ASSET_")
		name, value, ok2 := strings.Cut(rest, ", ")
		id, err := strconv.Atoi(value)
		if !ok || !ok2 || err != nil {
			t.Fatalf("bad line %q", line)
		}
		ids[name] = id
	}
	if len(ids) != len(m.Assets) {
		t.Fatalf("assets.inc has %d ids for %d assets", len(ids), len(m.Assets))
	}
	for _, a := range m.Assets {
		id, ok := ids[a.Name]
		if !ok {
			t.Errorf("no ASSET_%s", a.Name)
			continue
		}
		if id < 0 || id >= len(c.indx) {
			t.Errorf("ASSET_%s = %d, INDX has %d entries", a.Name, id, len(c.indx))
			continue
		}
		e := c.indx[id]
		if int(e.id) != id || e.typ != a.Type {
			t.Errorf("ASSET_%s = %d names INDX entry %s id %d, want %s", a.Name, id, e.typ, e.id, a.Type)
		}
	}
}
